"""Derive data/stimuli_783.json from Shiu et al.'s v630 stimulus sets (data/stimuli_630.json).

Most FlyWire root IDs are unchanged between v630 and v783. A neuron edited between the two
releases gets a new root ID. For each such neuron we find its v783 counterpart by comparing
synaptic partners: the weighted Ruzicka similarity sum(min) / sum(max) of its input and output
synapse counts per partner, over v783 neurons whose IDs are new in v783. A match is accepted
only if its score is >= 0.5 and at least twice the runner-up's. Every mapped neuron's v783
cell type and side are recorded from the FlyWire annotations for review.

    python scripts/fetch_data.py --group provenance
    python scripts/map_stimuli.py
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ascend import data  # noqa: E402

MIN_SCORE, MIN_RATIO = 0.5, 2.0


def partners(con: pd.DataFrame, i: int) -> pd.Series:
    out = con[con.Presynaptic_ID == i].groupby("Postsynaptic_ID").Connectivity.sum()
    inp = con[con.Postsynaptic_ID == i].groupby("Presynaptic_ID").Connectivity.sum()
    return pd.concat([out.rename(lambda x: ("out", x)), inp.rename(lambda x: ("in", x))])


def ruzicka(a: pd.Series, b: pd.Series) -> float:
    idx = a.index.union(b.index)
    x = a.reindex(idx, fill_value=0).to_numpy(float)
    y = b.reindex(idx, fill_value=0).to_numpy(float)
    return float(np.minimum(x, y).sum() / np.maximum(x, y).sum())


def match(old_id: int, con630: pd.DataFrame, con_new: pd.DataFrame, new_ids: set) -> list:
    v = partners(con630, old_id)
    post = [k[1] for k in v.index if k[0] == "out"]
    pre = [k[1] for k in v.index if k[0] == "in"]
    cand = set(con_new[con_new.Postsynaptic_ID.isin(post) & con_new.Presynaptic_ID.isin(new_ids)].Presynaptic_ID)
    cand |= set(con_new[con_new.Presynaptic_ID.isin(pre) & con_new.Postsynaptic_ID.isin(new_ids)].Postsynaptic_ID)
    scored = sorted(((ruzicka(v, partners(con_new, c)), int(c)) for c in cand), reverse=True)
    return scored[:3]


def main() -> int:
    src = json.loads((data.REPO_ROOT / "data" / "stimuli_630.json").read_text())
    ids783 = pd.read_csv(data.path("Completeness_783.csv"), index_col=0).index
    ids630 = set(pd.read_csv(data.path("Completeness_630.csv"), index_col=0).index)
    cols = ["Presynaptic_ID", "Postsynaptic_ID", "Connectivity"]
    con630 = pd.read_parquet(data.path("Connectivity_630.parquet"), columns=cols)
    con783 = pd.read_parquet(data.path("Connectivity_783.parquet"), columns=cols)
    ann = pd.read_csv(data.path("flywire_neuron_annotations.tsv"), sep="\t", low_memory=False).set_index("root_id")

    present = set(ids783)
    new_ids = present - ids630
    con_new = con783[con783.Presynaptic_ID.isin(new_ids) | con783.Postsynaptic_ID.isin(new_ids)]

    remap, ok = {}, True

    def resolve(i: int) -> int:
        nonlocal ok
        if i in present:
            return i
        if i not in remap:
            top = match(i, con630, con_new, new_ids)
            best, second = top[0][0] if top else 0.0, top[1][0] if len(top) > 1 else 0.0
            accepted = best >= MIN_SCORE and best >= MIN_RATIO * second
            remap[i] = {"v783": top[0][1] if top else None, "score": round(best, 4),
                        "runner_up": round(second, 4), "accepted": accepted}
            ok &= accepted
            print(f"{i} -> {remap[i]}")
        return remap[i]["v783"]

    def describe(i: int) -> dict:
        row = ann.loc[i] if i in ann.index else None
        f = (lambda k: None if row is None or pd.isna(row[k]) else str(row[k]))
        return {"id": i, "cell_type": f("cell_type"), "cell_sub_class": f("cell_sub_class"), "side": f("side")}

    out = {
        "description": "Stimulus and readout neurons for FlyWire v783. Generated by scripts/map_stimuli.py "
                       "from data/stimuli_630.json; do not edit by hand.",
        "source": src["source"],
        "matching": {"method": "weighted Ruzicka similarity of synaptic partners", "min_score": MIN_SCORE,
                     "min_ratio_to_runner_up": MIN_RATIO},
        "stimuli": {k: [resolve(i) for i in v] for k, v in src["stimuli"].items()},
        "readouts": {k: resolve(v) for k, v in src["readouts"].items()},
        "remapped_v630_ids": {str(k): v for k, v in remap.items()},
    }
    out["annotations"] = {
        "stimuli": {k: pd.Series([describe(i)["cell_type"] for i in v]).value_counts().to_dict()
                    for k, v in out["stimuli"].items()},
        "stimulus_sides": {k: sorted({describe(i)["side"] or "?" for i in v}) for k, v in out["stimuli"].items()},
        "readouts": {k: describe(i) for k, i in out["readouts"].items()},
    }
    dest = data.REPO_ROOT / "data" / "stimuli_783.json"
    dest.write_text(json.dumps(out, indent=1) + "\n")
    print(f"wrote {dest}; all matches accepted: {ok}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
